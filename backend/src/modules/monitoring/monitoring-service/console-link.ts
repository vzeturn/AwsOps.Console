// ---- CloudWatch_Console_Link (Requirement 12.1, 12.2, 12.3) ----

export interface ConsoleLinkParams {
  region: string;
  namespace: string;
  metricName: string;
  dimensionName: string;
  dimensionValue: string;
}

/**
 * Fixed string markers used to build/parse `CloudWatch_Console_Link`, per the URL scheme defined
 * in design.md ("CloudWatch_Console_Link (Requirement 12)"). This is an unofficial URL scheme not
 * stably documented by AWS (see design.md) — `buildConsoleLink`/`parseConsoleLink` only guarantee
 * that the 5 input parameters round-trip correctly through this pair of functions (Property 10),
 * not that AWS will keep this console format forever.
 */
const CONSOLE_LINK_HOST_SUFFIX = '.console.aws.amazon.com/cloudwatch/home?region=';
const CONSOLE_LINK_HASH_PREFIX = "#metricsV2:graph=~(metrics~(~(~'";
const CONSOLE_LINK_PARAM_SEP = "~'";
const CONSOLE_LINK_METRICS_TAIL = "))~view~'timeSeries~region~'";
const CONSOLE_LINK_SUFFIX = ')';

/**
 * `encodeURIComponent` does NOT escape `~` and `'` (both characters are in `encodeURIComponent`'s
 * "unreserved" set) — but `~'` is exactly `CONSOLE_LINK_PARAM_SEP`, the fixed string marker used
 * to separate the 5 parameters in this URL scheme. If a parameter value contains `~` or `'`,
 * `encodeURIComponent` leaves them as-is → potentially creating an accidental `~'` substring
 * inside a parameter, which would make `parseConsoleLink` (`split(CONSOLE_LINK_PARAM_SEP)`) split
 * into the wrong number of parts and return `undefined` (losing the round-trip, Property 10).
 * Manually escape `~`→`%7E`/`'`→`%27` AFTER `encodeURIComponent` so the `~'` marker can never
 * appear inside an encoded parameter. `decodeURIComponent` in `parseConsoleLink` correctly decodes
 * `%7E`/`%27` back to `~`/`'` like any other `%XX` sequence — no change needed on the parse side.
 */
function encodeConsoleLinkParam(value: string): string {
  return encodeURIComponent(value).replace(/~/g, '%7E').replace(/'/g, '%27');
}

/**
 * Builds the `CloudWatch_Console_Link` URL per design.md's scheme, `encodeURIComponent`-ing each
 * variable part before embedding it in the URL (Requirement 12.2/12.3):
 * `https://{region}.console.aws.amazon.com/cloudwatch/home?region={region}#metricsV2:graph=~(metrics~(~(~'{namespace}~'{metricName}~'{dimensionName}~'{dimensionValue}))~view~'timeSeries~region~'{region})`
 */
export function buildConsoleLink({ region, namespace, metricName, dimensionName, dimensionValue }: ConsoleLinkParams): string {
  const encodedRegion = encodeConsoleLinkParam(region);
  const encodedNamespace = encodeConsoleLinkParam(namespace);
  const encodedMetricName = encodeConsoleLinkParam(metricName);
  const encodedDimensionName = encodeConsoleLinkParam(dimensionName);
  const encodedDimensionValue = encodeConsoleLinkParam(dimensionValue);

  return (
    `https://${encodedRegion}${CONSOLE_LINK_HOST_SUFFIX}${encodedRegion}` +
    `${CONSOLE_LINK_HASH_PREFIX}${encodedNamespace}${CONSOLE_LINK_PARAM_SEP}${encodedMetricName}` +
    `${CONSOLE_LINK_PARAM_SEP}${encodedDimensionName}${CONSOLE_LINK_PARAM_SEP}${encodedDimensionValue}` +
    `${CONSOLE_LINK_METRICS_TAIL}${encodedRegion}${CONSOLE_LINK_SUFFIX}`
  );
}

/**
 * The reverse parser of `buildConsoleLink` — used ONLY for property/unit test round-trips
 * (Property 10), not on the real request path. Extracts the 5 parameters back out of a URL
 * generated by `buildConsoleLink` ITSELF, based on the URL scheme's fixed string markers (avoids
 * one large regex, for readability and easier fault isolation when a marker doesn't match).
 * Returns `undefined` if the URL doesn't match the expected structure (e.g. the 3 `region`
 * positions in the URL don't agree with each other).
 */
export function parseConsoleLink(url: string): ConsoleLinkParams | undefined {
  if (!url.startsWith('https://')) return undefined;
  const afterScheme = url.slice('https://'.length);

  const hostSuffixIndex = afterScheme.indexOf(CONSOLE_LINK_HOST_SUFFIX);
  if (hostSuffixIndex === -1) return undefined;
  const encodedRegionFromHost = afterScheme.slice(0, hostSuffixIndex);
  const afterHostSuffix = afterScheme.slice(hostSuffixIndex + CONSOLE_LINK_HOST_SUFFIX.length);

  const hashPrefixIndex = afterHostSuffix.indexOf(CONSOLE_LINK_HASH_PREFIX);
  if (hashPrefixIndex === -1) return undefined;
  const encodedRegionFromQuery = afterHostSuffix.slice(0, hashPrefixIndex);
  const afterHashPrefix = afterHostSuffix.slice(hashPrefixIndex + CONSOLE_LINK_HASH_PREFIX.length);

  const metricsTailIndex = afterHashPrefix.indexOf(CONSOLE_LINK_METRICS_TAIL);
  if (metricsTailIndex === -1) return undefined;
  const paramsSegment = afterHashPrefix.slice(0, metricsTailIndex);
  const afterMetricsTail = afterHashPrefix.slice(metricsTailIndex + CONSOLE_LINK_METRICS_TAIL.length);

  if (!afterMetricsTail.endsWith(CONSOLE_LINK_SUFFIX)) return undefined;
  const encodedRegionFromTail = afterMetricsTail.slice(0, -CONSOLE_LINK_SUFFIX.length);

  const paramParts = paramsSegment.split(CONSOLE_LINK_PARAM_SEP);
  if (paramParts.length !== 4) return undefined;
  const [encodedNamespace, encodedMetricName, encodedDimensionName, encodedDimensionValue] = paramParts;

  // The 3 region positions in the URL must agree — otherwise the URL wasn't produced by buildConsoleLink.
  if (encodedRegionFromHost !== encodedRegionFromQuery || encodedRegionFromHost !== encodedRegionFromTail) {
    return undefined;
  }

  try {
    return {
      region: decodeURIComponent(encodedRegionFromHost),
      namespace: decodeURIComponent(encodedNamespace),
      metricName: decodeURIComponent(encodedMetricName),
      dimensionName: decodeURIComponent(encodedDimensionName),
      dimensionValue: decodeURIComponent(encodedDimensionValue),
    };
  } catch {
    return undefined; // decodeURIComponent errored (invalid %-encoding) — treat as unparseable.
  }
}
