// ---- Arbitraries ----

const ALARM_STATES = ['OK', 'ALARM', 'INSUFFICIENT_DATA'] as const;

const EXPECTED_LEVEL: Record<(typeof ALARM_STATES)[number], 'ok' | 'warn' | 'critical'> = {
  OK: 'ok',
  ALARM: 'critical',
  INSUFFICIENT_DATA: 'warn',
};

const nameArb = fc.string({ minLength: 1, maxLength: 20 }).filter((s) => s.trim().length > 0);

// Dimensions: arbitrary Name/Value pairs — no need to match any resource-identifying names for
// this property (only checks the alarmName/state/namespace/threshold.level pass-through).
const dimensionsArb = fc.array(
  fc.record({ Name: nameArb, Value: nameArb }),
  { minLength: 0, maxLength: 3 },
);

/**
 * 1 alarm spec — AlarmName uses the index as a prefix to guarantee uniqueness across the whole
 * generated array (avoids 2 alarms with the same name making the 1-to-1 input/output matching
 * ambiguous; this is a constraint of the test itself, not of alert-service.ts).
 */
const alarmSpecArb = fc.record({
  namePart: nameArb,
  state: fc.constantFrom(...ALARM_STATES),
  namespace: nameArb,
  dimensions: dimensionsArb,
});

const alarmSpecsArb = fc
  .array(alarmSpecArb, { minLength: 0, maxLength: 10 })
  .map((specs) => specs.map((spec, idx) => ({ ...spec, alarmName: `${idx}-${spec.namePart}` })));

interface AlarmSpec {
  alarmName: string;
  state: (typeof ALARM_STATES)[number];
  namespace: string;
  dimensions: { Name: string; Value: string }[];
}

function setupCloudWatchMock(specs: AlarmSpec[]) {
  cwSendMock.mockImplementation(async (command: { __type?: string }) => {
    if (command.__type === 'DescribeAlarms') {
      return {
        MetricAlarms: specs.map((spec) => ({
          AlarmName: spec.alarmName,
          StateValue: spec.state,
          Namespace: spec.namespace,
          Dimensions: spec.dimensions,
        })),
        NextToken: undefined,
      };
    }
    return {};
  });
}

describe('Alarm state pass-through and level mapping (Property 7)', () => {
  it('each alarm produces exactly 1 AlarmSummary, preserving alarmName/state/namespace, with threshold.level correctly derived from state', async () => {
    await fc.assert(
      fc.asyncProperty(alarmSpecsArb, async (specs) => {
        setupCloudWatchMock(specs);

        const summaries = await getAlerts();

        // No alarm is dropped — every alarm (each has an AlarmName + StateValue) produces exactly
        // 1 AlarmSummary.
        expect(summaries).toHaveLength(specs.length);

        for (const spec of specs) {
          const matches = summaries.filter((s) => s.alarmName === spec.alarmName);
          expect(matches).toHaveLength(1);

          const summary = matches[0];
          expect(summary.state).toBe(spec.state);
          expect(summary.namespace).toBe(spec.namespace);
          expect(summary.threshold.level).toBe(EXPECTED_LEVEL[spec.state]);
        }
      }),
      { numRuns: 100 },
    );
  });
});
