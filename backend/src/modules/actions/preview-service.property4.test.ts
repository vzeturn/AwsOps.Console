const CATALOG_ENTRIES_FOR_RECOMMENDATION_PATH = ACTION_CATALOG.filter(
  (entry) => !DIRECT_ONLY_ACTION_TYPES.includes(entry.actionType),
);

/**
 * Generates 1 RecommendationItem whose (category, resourceType) matches EXACTLY 1 of the 4 real
 * ACTION_CATALOG entries (the correct scope of this property — "catalog-matched"), with a
 * corresponding valid AWS state ('found' for the EBS volume; 'success'/'notFound' for the S3
 * lifecycle — both are valid states that preview-service.ts handles gracefully, see
 * buildS3LifecyclePreview).
 */
// The findingType corresponds EXACTLY to the entry's actionType — it only needs to be CONSISTENT
// with the generated entry (this test does not check the findingType selection logic, only that
// buildActionPreview() resolves the expected entry). EC2_Start/EC2_Stop use any findingType with NO
// explicit override (falls back through matchActionCatalog by category/resourceType, unchanged old
// behavior).
const FINDING_TYPE_BY_ACTION_TYPE: Partial<Record<ActionType, RecommendationItem['findingType']>> = {
  Snapshot_And_Delete_EBS_Volume: 'ebsVolumeUnattached',
  Apply_S3_Lifecycle_Policy: 's3BucketNoLifecyclePolicy',
  EC2_Start: 'ec2Stopped',
  EC2_Stop: 'ec2Stopped',
};

const matchedRecommendationArb = fc
  .record({
    entry: fc.constantFrom(...CATALOG_ENTRIES_FOR_RECOMMENDATION_PATH),
    id: nonEmptyStringArb,
    resourceId: nonEmptyStringArb,
    resourceName: nonEmptyStringArb,
    currentState: nonEmptyStringArb,
    recommendedAction: nonEmptyStringArb,
    estimatedMonthlySavingsUsd: fc.option(fc.integer({ min: 0, max: 10_000 }), { nil: null }),
    risk: fc.constantFrom(...RISK_LEVELS),
    priority: fc.constantFrom(...PRIORITIES),
    lifecycleOutcome: fc.constantFrom<'success' | 'notFound'>('success', 'notFound'),
  })
  .map((spec) => {
    const item: RecommendationItem = {
      id: spec.id,
      category: spec.entry.category,
      resourceType: spec.entry.resourceType,
      resourceId: spec.resourceId,
      resourceName: spec.resourceName,
      currentState: spec.currentState,
      recommendedAction: spec.recommendedAction,
      estimatedMonthlySavingsUsd: spec.estimatedMonthlySavingsUsd,
      risk: spec.risk,
      priority: spec.priority,
      findingType: FINDING_TYPE_BY_ACTION_TYPE[spec.entry.actionType] ?? 'ec2Stopped',
    };
    // matchActionCatalog uses Array.find by (category, resourceType) — EC2_Start and EC2_Stop share
    // the SAME (category: 'compute', resourceType: 'ec2-instance'), so for an EC2 item the entry
    // actually matched is ALWAYS the first EC2 entry in ACTION_CATALOG (EC2_Start), regardless of
    // whether spec.entry generated EC2_Start or EC2_Stop. Derive the expected entry via the real
    // matchActionCatalog() (the single source of truth) instead of assuming spec.entry — avoids a
    // false counterexample for this property.
    const matchedEntry = matchActionCatalog(item);
    if (!matchedEntry) {
      throw new Error('Test setup invariant violated: generated item must match ACTION_CATALOG');
    }
    return { item, entry: matchedEntry, lifecycleOutcome: spec.lifecycleOutcome };
  });

function buildFakeReport(item: RecommendationItem): AssessmentReport {
  return {
    account: '123456789012',
    region: 'ap-southeast-1',
    periodStart: '2024-01-01',
    periodEnd: '2024-01-31',
    generatedAt: '2024-02-01T00:00:00.000Z',
    compute: { lambda: [] },
    database: {},
    networking: { natGateways: [] },
    storage: { s3Buckets: [], ebsVolumes: [] },
    savingsPlans: { coverageByService: [] },
    backup: { protectionGaps: [] },
    recommendations: [item],
  };
}

function setupMocks(
  item: RecommendationItem,
  report: AssessmentReport,
  lifecycleOutcome: 'success' | 'notFound',
) {
  s3SendMock.mockImplementation(async (command: { __type?: string }) => {
    if (command.__type === 'GetObject') {
      return { Body: { transformToString: async () => JSON.stringify(report) } };
    }
    if (command.__type === 'GetBucketLifecycleConfiguration') {
      if (lifecycleOutcome === 'notFound') {
        const err = new Error('The lifecycle configuration does not exist');
        err.name = 'NoSuchLifecycleConfiguration';
        throw err;
      }
      return {};
    }
    throw new Error(`Unexpected S3 command in test mock: ${command.__type}`);
  });

  ec2SendMock.mockImplementation(async (command: { __type?: string }) => {
    if (command.__type === 'DescribeVolumes') {
      return { Volumes: [{ VolumeId: item.resourceId }] };
    }
    throw new Error(`Unexpected EC2 command in test mock: ${command.__type}`);
  });
}

describe('Action preview is complete for every catalog-matched action (Property 4)', () => {
  it('buildActionPreview returns a complete ActionPreview with correct identifiers and the exact param set for every RecommendationItem matching Action_Catalog', async () => {
    await fc.assert(
      fc.asyncProperty(matchedRecommendationArb, async ({ item, entry, lifecycleOutcome }) => {
        const report = buildFakeReport(item);
        setupMocks(item, report, lifecycleOutcome);

        const preview = await buildActionPreview(item.id);

        // awsApiCall: a non-empty string, specific to the actionType.
        expect(typeof preview.awsApiCall).toBe('string');
        expect(preview.awsApiCall.length).toBeGreaterThan(0);

        // resource.id/region match the identifiers derived from the input; arn matches the region
        // and contains the resourceId.
        expect(preview.resource.id).toBe(item.resourceId);
        expect(preview.resource.region).toBe('ap-southeast-1');
        expect(typeof preview.resource.arn).toBe('string');
        expect(preview.resource.arn.length).toBeGreaterThan(0);
        expect(preview.resource.arn.includes(item.resourceId)).toBe(true);

        // params: a non-null object, matching EXACTLY the key set defined for the actionType (no
        // extra, no missing keys).
        expect(preview.params).toBeDefined();
        expect(preview.params).not.toBeNull();
        expect(Object.keys(preview.params).sort()).toEqual(
          [...EXPECTED_PARAM_KEYS[preview.actionType]].sort(),
        );

        // reversibilityClass matches the corresponding Action_Catalog entry.
        expect(preview.reversibilityClass).toBe(entry.reversibilityClass);
        expect(preview.actionType).toBe(entry.actionType);
      }),
      { numRuns: 150 },
    );
  });
});
